	// Move the existing default entry; never insert another flag or sort its peers.
	template<typename TEntries, typename FDefault>
	void PlayerDefaultFirst(TEntries &Entries, FDefault IsDefault)
	{
		const auto Default = std::find_if(Entries.begin(), Entries.end(), IsDefault);
		if(Default != Entries.end())
			std::rotate(Entries.begin(), Default, std::next(Default));
	}

